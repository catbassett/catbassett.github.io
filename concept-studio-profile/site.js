function currentRoots() {
  const body = document.body;
  return {
    assetRoot: body.dataset.assetRoot || "..",
    siteRoot: body.dataset.siteRoot || "."
  };
}

function joinPath(root, path) {
  return `${root}/${path}`.replace(/\/+/g, "/");
}

function siteUrl(slug) {
  const { siteRoot } = currentRoots();
  if (slug === "home") {
    return joinPath(siteRoot, "index.html");
  }
  return joinPath(siteRoot, `${slug}/index.html`);
}

function assetUrl(path) {
  const { assetRoot } = currentRoots();
  return joinPath(assetRoot, path);
}

function topNav(active) {
  return `
    <div class="link-row">
      <a class="pill ${active === "home" ? "is-active" : ""}" href="${siteUrl("home")}">Portfolio Home</a>
      <a class="pill ${active === "about" ? "is-active" : ""}" href="${siteUrl("about")}">About</a>
    </div>
  `;
}

